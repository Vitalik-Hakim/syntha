"""Golden synthetic markets (PRD §17.1).

Every expected value in tests/golden/*/fixture.json was derived by hand; the arithmetic is
written out in each fixture's `derivation`. They were not generated by running the engine. If one
of these fails, find out whether the engine or the derivation is wrong before changing anything.
Numbers are compared as exact Decimals, which is stricter than "to the cent".
"""

from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest

from syntha_engine.runner import run
from syntha_worker.fixtures import Fixture, load_fixture

GOLDEN = Path(__file__).parent / "golden"
FIXTURES = sorted(p.name for p in GOLDEN.iterdir() if (p / "fixture.json").exists())

# Required by PRD §17.1; the test suite fails if any is missing.
REQUIRED = {
    "single_trade_tp",
    "single_trade_resolution",
    "losing_resolution",
    "invalid_resolution",
    "cash_constrained",
    "exposure_capped",
    "min_size_rejected",
    "no_liquidity",
    "partial_fill",
    "compounding",
    "fee_schedule_change",
    "stale_data",
    # PRD v3 §3 (M8 acceptance)
    "limit_fill",
    "limit_expired",
    "same_side_cap",
    "both_side_liquidity",
    "basket_all_or_nothing",
    "wallet_sell",
}


def test_all_prd_fixtures_exist() -> None:
    assert set(FIXTURES) >= REQUIRED


def _actual(fx: Fixture, trade: dict[str, Any], key: str) -> Any:
    entry = trade["entry_rule_trace"] or {}
    sizing = entry.get("sizing") or {}
    execution = entry.get("execution") or {}
    exit_trace = trade["exit_rule_trace"] or {}
    if key.endswith("_minute"):
        ts = trade[key.replace("_minute", "_ts")]
        return None if ts is None else fx.minute(ts)
    if key in ("size_binding_constraint", "requested_notional", "final_notional"):
        return sizing.get(key)
    if key == "attempts":
        return entry.get("attempts")
    if key == "attempted_shares":
        return execution.get("shares")
    if key == "reason":
        return execution.get("reason")
    if key == "settled_on_stale_data":
        return (exit_trace.get("flags") or {}).get(key, False)
    return trade[key]


def _same(expected: Any, actual: Any) -> bool:
    if isinstance(expected, str) and isinstance(actual, str):
        try:
            return Decimal(expected) == Decimal(actual)
        except ArithmeticError:
            return expected == actual
    return bool(expected == actual)


@pytest.mark.parametrize("name", FIXTURES)
def test_golden(name: str) -> None:
    fx = load_fixture(GOLDEN / name)
    result = run(fx.request, fx.dataset, fx.settlement)
    exp = fx.expected

    cash_end = result.ledger[-1]["running_cash"]
    equity_end = result.equity[-1]["equity"]
    problems: list[str] = []
    if not _same(exp["cash_end"], cash_end):
        problems.append(f"cash_end: expected {exp['cash_end']}, got {cash_end}")
    if not _same(exp["equity_end"], equity_end):
        problems.append(f"equity_end: expected {exp['equity_end']}, got {equity_end}")

    if len(result.trades) != len(exp["trades"]):
        problems.append(
            f"expected {len(exp['trades'])} trades, got {len(result.trades)}: "
            f"{[(t['seq'], t['fill_status']) for t in result.trades]}"
        )
    for want, got in zip(exp["trades"], result.trades, strict=False):
        for key, value in want.items():
            actual = _actual(fx, got, key)
            if not _same(value, actual):
                problems.append(
                    f"trade {want.get('seq')} {key}: expected {value!r}, got {actual!r}"
                )

    for key, value in exp.get("data_quality", {}).items():
        actual = result.data_quality.get(key)
        if not _same(value, actual):
            problems.append(f"data_quality.{key}: expected {value!r}, got {actual!r}")

    assert not problems, f"{name}:\n  " + "\n  ".join(problems)
